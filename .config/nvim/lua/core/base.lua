-- ============================================================================
-- エンコーディング設定
-- ============================================================================
vim.opt.encoding = "utf-8" -- Vim内部で使用する文字エンコーディング
vim.opt.fileencoding = "utf-8" -- 新規ファイル保存時のデフォルト文字エンコーディング
vim.scriptencoding = "utf-8" -- Luaではなく、このVimスクリプト自体のエンコーディング指定
vim.opt.fileformats = "unix,dos,mac" -- 改行コードの自動判別順序（LF, CRLF, CR）
vim.opt.ambiwidth = "single" -- 曖昧幅文字（□や○など）の幅を1文字分として扱う

-- ============================================================================
-- 表示・UI設定
-- ============================================================================
vim.opt.number = true -- 行番号を表示
vim.opt.showmatch = true -- 対応する括弧を強調表示
vim.opt.matchtime = 1 -- showmatchの強調表示時間（1 = 0.1秒）
vim.opt.showtabline = 2 -- タブラインを常に表示（0=非表示, 1=2つ以上で表示, 2=常に表示）
vim.opt.showmode = false -- モード表示を非表示（INSERT、VISUALなどの表示を消す）
vim.opt.cursorline = true -- カーソル行をハイライト表示
vim.opt.termguicolors = true -- 24bitカラー（True Color）を有効化
vim.opt.hlsearch = true -- 検索結果をハイライト表示
vim.opt.scrolloff = 5 -- スクロール時に上下に最低5行の余白を保つ
vim.opt.signcolumn = "yes" -- 行番号の左側にサイン列を常に表示（gitの変更マークなど用）
vim.opt.wrap = false -- 長い行を折り返さない
vim.opt.pumblend = 0 -- ポップアップメニューの透明度（0=不透明, 100=完全透明）
vim.opt.winblend = 0 -- フローティングウィンドウの透明度（0=不透明, 100=完全透明）
vim.opt.laststatus = 3 -- ステータスラインの表示方法（3=グローバルステータスライン）
vim.opt.wildoptions = "pum" -- コマンドライン補完をポップアップメニューで表示

-- ============================================================================
-- インデント・タブ設定
-- ============================================================================
vim.opt.smartindent = true -- 新しい行で自動的にインデントを挿入
vim.opt.expandtab = true -- タブ入力をスペースに展開
vim.opt.tabstop = 2 -- タブ文字の表示幅を2スペース分に設定
vim.opt.shiftwidth = 2 -- 自動インデントや>>、<<の幅を2スペースに設定

-- ============================================================================
-- 検索設定
-- ============================================================================
vim.opt.ignorecase = true -- 検索時に大文字小文字を区別しない
vim.opt.smartcase = true -- 検索文字列に大文字が含まれる場合のみ区別する
vim.opt.wrapscan = true -- 検索がファイル末尾に達したら先頭から再検索

-- ============================================================================
-- 編集動作設定
-- ============================================================================
vim.opt.clipboard = "unnamedplus" -- システムクリップボードを使用（"+レジスタを無名レジスタと統合）
vim.opt.mouse = "a" -- 全モードでマウス操作を有効化
vim.opt.backspace = { "start", "eol", "indent" } -- バックスペースで削除可能な要素を指定
-- start=挿入開始位置より前、eol=改行、indent=自動インデント

-- ============================================================================
-- ファイル管理設定
-- ============================================================================
vim.opt.swapfile = false -- スワップファイルを作成しない
vim.opt.autoread = true -- 外部でファイルが編集された場合に自動で反映する

-- ============================================================================
-- 折りたたみ設定
-- ============================================================================
vim.o.foldlevel = 99 -- 初期状態で折りたたむレベル（99=ほぼ全て展開）
vim.o.foldlevelstart = 99 -- ファイルを開いた時の折りたたみレベル
vim.o.foldenable = true -- 折りたたみ機能を有効化
